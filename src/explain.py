"""LIME explainability module for DistilBERT emotion classification.

Provides local interpretable model-agnostic explanations (LIME) for model predictions,
with batched inference, robust empty-string handling, HTML exports, and bar-chart visualizations.
"""

from typing import Any, Optional, Union
from pathlib import Path
import time
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import torch
from lime.lime_text import LimeTextExplainer
from transformers import AutoModelForSequenceClassification, AutoTokenizer

from src.config import (
    ACTIVE_DISTILBERT,
    ACTIVE_DISTILBERT_DIR,
    FIGURES_DIR,
    LABELS,
    MAX_LENGTH,
    METRICS_DIR,
    MODEL_DIRS,
    MODELS_DIR,
    SEED,
)
from src.preprocess import minimal_clean

# Module-level singletons for efficient inference reuse
_MODEL: Optional[AutoModelForSequenceClassification] = None
_TOKENIZER: Optional[AutoTokenizer] = None
_EXPLAINER: Optional[LimeTextExplainer] = None


def get_model_and_tokenizer(
    model_dir: Optional[Path] = None,
) -> tuple[AutoModelForSequenceClassification, AutoTokenizer]:
    """Load and cache DistilBERT model and tokenizer.

    Checks active model directory first (from src.config), falling back gracefully
    to other installed DistilBERT models if missing.

    Args:
        model_dir: Optional custom model directory path.

    Returns:
        Tuple of (model, tokenizer).
    """
    global _MODEL, _TOKENIZER
    if _MODEL is None or _TOKENIZER is None or model_dir is not None:
        target_dir = model_dir
        if target_dir is None:
            target_dir = ACTIVE_DISTILBERT_DIR
            if not target_dir.exists():
                v1_dir = MODEL_DIRS.get("distilbert")
                if v1_dir and v1_dir.exists():
                    target_dir = v1_dir

        if not target_dir.exists():
            raise FileNotFoundError(
                f"No trained DistilBERT model found in {target_dir}. "
                "Please run `python -m src.download_models` to download models."
            )

        tokenizer = AutoTokenizer.from_pretrained(str(target_dir))
        model = AutoModelForSequenceClassification.from_pretrained(str(target_dir))
        model.eval()

        if model_dir is None:
            _MODEL = model
            _TOKENIZER = tokenizer
        return model, tokenizer

    return _MODEL, _TOKENIZER


def get_explainer() -> LimeTextExplainer:
    """Retrieve or initialize LimeTextExplainer singleton."""
    global _EXPLAINER
    if _EXPLAINER is None:
        _EXPLAINER = LimeTextExplainer(
            class_names=LABELS,
            random_state=SEED,
            bow=False,
        )
    return _EXPLAINER


def predict_proba(
    texts: list[str],
    batch_size: int = 32,
    model_dir: Optional[Path] = None,
) -> np.ndarray:
    """Compute batched class probabilities for a list of texts in config.LABELS order.

    Robustly handles empty strings or whitespace perturbed texts generated by LIME.

    Args:
        texts: List of text strings to classify.
        batch_size: Inference mini-batch size (default: 32).
        model_dir: Optional custom model directory path.

    Returns:
        Numpy array of shape (len(texts), 6) with probabilities in config.LABELS order.
    """
    model, tokenizer = get_model_and_tokenizer(model_dir)

    # Clean texts while protecting against empty strings generated by LIME word masks
    safe_texts: list[str] = []
    for t in texts:
        if t is None or not isinstance(t, str):
            safe_texts.append(" ")
        else:
            cleaned = minimal_clean(t)
            safe_texts.append(cleaned if cleaned.strip() else " ")

    all_probs: list[np.ndarray] = []

    with torch.no_grad():
        for i in range(0, len(safe_texts), batch_size):
            batch = safe_texts[i : i + batch_size]
            encoded = tokenizer(
                batch,
                padding=True,
                truncation=True,
                max_length=MAX_LENGTH,
                return_tensors="pt",
            )
            outputs = model(**encoded)
            probs = torch.softmax(outputs.logits, dim=1).cpu().numpy()
            all_probs.append(probs)

    if not all_probs:
        return np.zeros((0, len(LABELS)))

    return np.vstack(all_probs)


def explain_text(
    text: Optional[str],
    num_samples: int = 500,
    num_features: int = 8,
    model_dir: Optional[Path] = None,
) -> dict[str, Any]:
    """Generate LIME explanation for an input text.

    Args:
        text: Raw text string to explain.
        num_samples: Number of perturbed samples for LIME local surrogate (default: 500).
        num_features: Maximum number of influential features to return (default: 8).
        model_dir: Optional custom model directory path.

    Returns:
        Dictionary containing:
        - 'error': Optional error message if input is empty or invalid.
        - 'predicted_label': String emotion label.
        - 'probabilities': Dict mapping each emotion label to float probability.
        - 'weights': List of (word, weight) tuples for predicted class.
        - 'explanation': Raw LIME Explanation object (if successful).
    """
    if text is None or not isinstance(text, str) or not text.strip():
        return {
            "error": "Input text cannot be empty or whitespace.",
            "predicted_label": "",
            "probabilities": {},
            "weights": [],
            "explanation": None,
        }

    try:
        get_model_and_tokenizer(model_dir)
    except FileNotFoundError as fnf_err:
        return {
            "error": (
                f"Model weights are not available: {fnf_err}\n"
                "Please run `python -m src.download_models` to download models."
            ),
            "predicted_label": "",
            "probabilities": {},
            "weights": [],
            "explanation": None,
        }

    explainer = get_explainer()

    def _predict_fn(batch_texts: list[str]) -> np.ndarray:
        return predict_proba(batch_texts, batch_size=32, model_dir=model_dir)

    # Determine predicted class index from unperturbed text
    initial_probs = _predict_fn([text])[0]
    pred_idx = int(np.argmax(initial_probs))
    pred_label = LABELS[pred_idx]

    # Generate explanation for the predicted class
    exp = explainer.explain_instance(
        text,
        _predict_fn,
        labels=[pred_idx],
        num_features=num_features,
        num_samples=num_samples,
    )

    weights = [(word, float(weight)) for word, weight in exp.as_list(label=pred_idx)]
    prob_dict = {label: float(initial_probs[i]) for i, label in enumerate(LABELS)}

    return {
        "error": None,
        "predicted_label": pred_label,
        "probabilities": prob_dict,
        "weights": weights,
        "explanation": exp,
    }


def save_explanation(
    text_or_explanation: Union[str, Any],
    path: Path,
    num_samples: int = 500,
    num_features: int = 8,
    model_dir: Optional[Path] = None,
) -> Path:
    """Save LIME explanation as an interactive HTML file.

    Args:
        text_or_explanation: Raw text string or pre-computed LIME Explanation instance.
        path: Output destination path for the HTML file.
        num_samples: Perturbation samples if text is passed.
        num_features: Number of features if text is passed.
        model_dir: Optional custom model directory.

    Returns:
        Path to the saved HTML file.
    """
    path.parent.mkdir(parents=True, exist_ok=True)

    if isinstance(text_or_explanation, str):
        if not text_or_explanation or not text_or_explanation.strip():
            raise ValueError("Cannot explain or save empty or whitespace text.")
        res = explain_text(
            text_or_explanation,
            num_samples=num_samples,
            num_features=num_features,
            model_dir=model_dir,
        )
        exp = res["explanation"]
    else:
        exp = text_or_explanation

    exp.save_to_file(str(path))
    return path


def plot_explanation_barchart(
    weights: list[tuple[str, float]],
    predicted_label: str,
    confidence: float,
    output_path: Path,
    title_suffix: str = "",
) -> Path:
    """Generate and save horizontal bar chart of LIME word contributions.

    Args:
        weights: List of (word, weight) tuples.
        predicted_label: Predicted emotion label string.
        confidence: Prediction confidence score (0.0 to 1.0).
        output_path: Path for saving PNG image.
        title_suffix: Optional extra text in plot title.

    Returns:
        Path to the saved PNG file.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)

    fig, ax = plt.subplots(figsize=(8, 4.5))
    words = [w for w, _ in weights]
    scores = [s for _, s in weights]

    # Invert to place highest positive feature on top
    words_rev = list(reversed(words))
    scores_rev = list(reversed(scores))

    colors = ["#2ca02c" if s >= 0 else "#d62728" for s in scores_rev]
    y_pos = np.arange(len(words_rev))

    ax.barh(y_pos, scores_rev, color=colors, height=0.6)
    ax.set_yticks(y_pos)
    ax.set_yticklabels(words_rev, fontsize=10)
    ax.axvline(0, color="black", linestyle="--", linewidth=0.8, alpha=0.7)
    ax.set_xlabel("LIME Feature Weight (Contribution to Prediction)")

    title = f"LIME Explanation: '{predicted_label}' (Conf: {confidence:.2f})"
    if title_suffix:
        title += f" - {title_suffix}"
    ax.set_title(title, fontsize=11, fontweight="bold")
    ax.grid(axis="x", linestyle="--", alpha=0.5)

    plt.tight_layout()
    fig.savefig(output_path, dpi=300)
    plt.close(fig)
    return output_path


def run_explanations_demo() -> list[dict[str, Any]]:
    """Generate and export LIME HTML and PNG explanations for 5 benchmark examples.

    Includes at least one misclassified example extracted from top error metrics.

    Returns:
        List of result dictionaries for each of the 5 examples.
    """
    print("\n==================================================")
    print("Generating LIME Explanations for 5 Benchmark Texts")
    print("==================================================\n")

    # Select misclassified sample from top errors CSV
    error_csv = METRICS_DIR / f"{ACTIVE_DISTILBERT}_top_errors.csv"
    if not error_csv.exists():
        error_csv = METRICS_DIR / "distilbert_top_errors.csv"

    misclassified_text = (
        "i received the blanket i was absolutely amazed on how fluffy it is and extremely soft "
        "i really didnt think it was going to feel that amazing"
    )
    misclassified_note = "Misclassified (True: surprise -> Pred: joy)"

    if error_csv.exists():
        try:
            df_err = pd.read_csv(error_csv)
            if not df_err.empty:
                misclassified_text = df_err.iloc[0]["text"]
                true_l = df_err.iloc[0]["true_label"]
                pred_l = df_err.iloc[0]["pred_label"]
                misclassified_note = f"Misclassified (True: {true_l} -> Pred: {pred_l})"
        except Exception as e:
            print(f"Note: Error reading error CSV ({e}), using default misclassified instance.")

    examples = [
        (
            misclassified_text,
            misclassified_note,
        ),
        (
            "im feeling rather rotten so im not very ambitious right now",
            "Sadness sample",
        ),
        (
            "i am feeling really happy and content with where my life is right now",
            "Joy sample",
        ),
        (
            "i am feeling furious that they cancelled the flight without any warning",
            "Anger sample",
        ),
        (
            "i feel terrified walking alone in this dark and eerie alley",
            "Fear sample",
        ),
    ]

    results: list[dict[str, Any]] = []
    durations: list[float] = []

    for i, (text, note) in enumerate(examples, 1):
        print(f"[{i}/5] Explaining: \"{text[:55]}...\" ({note})")
        t0 = time.perf_counter()
        res = explain_text(text, num_samples=500, num_features=8)
        elapsed = time.perf_counter() - t0
        durations.append(elapsed)

        pred_lbl = res["predicted_label"]
        conf = res["probabilities"].get(pred_lbl, 0.0)
        exp = res["explanation"]

        # Save HTML
        html_path = FIGURES_DIR / f"lime_example_{i}.html"
        save_explanation(exp, html_path)

        # Save PNG
        png_path = FIGURES_DIR / f"lime_example_{i}.png"
        plot_explanation_barchart(res["weights"], pred_lbl, conf, png_path, title_suffix=note)

        print(f"  -> Predicted: '{pred_lbl}' (Confidence: {conf:.2f}) in {elapsed:.2f}s")
        print(f"  -> Top features: {res['weights'][:4]}")
        print(f"  -> Saved to {html_path.name} and {png_path.name}\n")

        res_record = {
            "index": i,
            "text": text,
            "note": note,
            "predicted_label": pred_lbl,
            "confidence": conf,
            "duration_seconds": elapsed,
            "weights": res["weights"],
            "html_path": str(html_path),
            "png_path": str(png_path),
        }
        results.append(res_record)

    avg_time = sum(durations) / len(durations)
    print(f"Average time per explanation (500 samples): {avg_time:.2f} seconds.")
    return results


if __name__ == "__main__":
    run_explanations_demo()
